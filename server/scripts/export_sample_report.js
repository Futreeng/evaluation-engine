/**
 * Export a report as public/sample-report.js — the read-only sample that
 * powers the landing card and #/report/sample.
 *
 *   node scripts/export_sample_report.js <report_id>
 *
 * Only use a report for an account whose owner has agreed to be the sample.
 * Strips email, account and payment metadata; keeps everything the report
 * page renders (scores, posts, moves, calendar, competitors).
 */
const path = require("path");
const fs = require("fs");
require("dotenv").config({ path: path.join(__dirname, "..", ".env") });
const geDb = require("../growth_engine_db_select");

const DROP = ["email", "account_id", "accountId", "one_time_unlock", "moves_done", "refresh_due_at", "raw_personas", "history", "upsell", "competitor_handles", "checkins", "nudge", "nudges_sent", "emails_sent", "plan_started_at"];

async function main() {
  const id = process.argv[2];
  if (!id) { console.error("usage: node scripts/export_sample_report.js <report_id>"); process.exit(1); }
  await geDb.initDb();
  const rep = await geDb.getReport(id);
  if (!rep) { console.error(`report ${id} not found`); process.exit(1); }
  const body = { ...(rep.reportBody || rep.report_body || {}) };
  for (const k of DROP) delete body[k];
  body.report_id = "sample";
  body.tier = rep.tier || body.tier || "growth_plan";
  body.created_at = body.created_at || body.generated_at || rep.generatedAt || rep.generated_at || Date.now();
  body.business = { ...(rep.business || body.business || {}) };
  delete body.business.email;
  if (body.plan_context) delete body.plan_context.updated_at;
  if (body.competitors && body.competitors.you) body.competitors.you = { handle: body.business.handle, overall: body.scores?.overall };
  body.sample = true;
  const strip = (arr) => Array.isArray(arr) ? arr.map((x) => String(x).replace(/^\s*(?:step\s*)?\d+[.)]\s*/i, "").trim()) : arr;
  (body.growth_path?.phases || []).forEach((p) => { if (p.opener) p.opener.how = strip(p.opener.how); (p.moves || []).forEach((m) => { m.how = strip(m.how); }); });
  // Moves read 02–13 in order (01 is each phase's opener).
  (body.growth_path?.phases || []).forEach((p, i) => (p.moves || []).forEach((m, k) => { m.n = i * 4 + k + 2; }));
  // The LLM occasionally echoes a literal "null" from the profile data
  // ("website is set to null"). Read it as a person would.
  const scrub = (v) => typeof v === "string" ? v.replace(/\b(set to|shows|is|currently) null\b/gi, (m, w) => `${w} empty`).replace(/\bnull\b/g, "empty") : Array.isArray(v) ? v.map(scrub) : v && typeof v === "object" ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, scrub(x)])) : v;
  Object.assign(body, scrub(body));

  const out = path.join(__dirname, "..", "..", "public", "sample-report.js");
  const header = `// Generated by server/scripts/export_sample_report.js from report ${id} on ${new Date().toISOString().slice(0, 10)}.\n// A real Growth Plan report, shown with the account owner's permission. Do not edit by hand.\n`;
  fs.writeFileSync(out, header + "window.SCALECRAFT_SAMPLE = " + JSON.stringify(body, null, 1) + ";\n");
  console.log(`wrote ${out} — @${body.business.handle} ${body.business.platform} score ${body.scores?.overall}, ${(body.growth_path?.phases || []).reduce((n, p) => n + 1 + (p.moves || []).length, 0)} moves, ${(body.calendar?.weeks || []).length} weeks, ${(body.competitors?.competitors || []).length} competitors`);
  process.exit(0);
}
main().catch((e) => { console.error(e); process.exit(1); });
