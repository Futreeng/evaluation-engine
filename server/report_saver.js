/**
 * Report Saver
 * Saves generated reports as markdown files for review and frontend reference
 */

const fs = require("fs");
const path = require("path");

const REPORTS_DIR = path.join(__dirname, "..", "reports");

function ensureReportsDir() {
  if (!fs.existsSync(REPORTS_DIR)) {
    fs.mkdirSync(REPORTS_DIR, { recursive: true });
  }
}

function saveReportAsMarkdown(handle, platform, narrative) {
  ensureReportsDir();

  const timestamp = new Date().toISOString().split("T")[0];
  const filename = `${handle}_${platform}_${timestamp}.md`;
  const filepath = path.join(REPORTS_DIR, filename);

  const markdown = `# Social Media Audit Report

**Handle:** @${handle}
**Platform:** ${platform}
**Generated:** ${new Date().toLocaleString()}

---

${narrative}

---

*Report generated by futureEng Growth Engine*
`;

  fs.writeFileSync(filepath, markdown);
  console.log(`[Report Saver] Saved: ${filepath}`);
  return filepath;
}

module.exports = {
  saveReportAsMarkdown,
};
